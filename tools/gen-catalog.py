def github_link(repo):
    return "[%s](https://github.com/%s)" % (repo, repo)


def source_text(kit, vis):
    """The 'Source' value for a card: links only for public repositories, nothing else about where the rest live."""
    states = [(r, vis.get(r, ("unknown", "unknown"))[0]) for r in kit.repos]
    if not states:
        return "Repository not created yet"
    public = [r for r, v in states if v == "public"]
    others = [v for _, v in states if v != "public"]
    if public:
        text = ", ".join(github_link(r) for r in public)
        if others:
            text += " (other repositories of this Kit are not public yet)"
        return text
    if all(v == "missing" for _, v in states):
        return "Repository not created yet"
    return "not public yet"


def source_cell(kit, vis):
    return md_escape_cell(source_text(kit, vis))


def has_public_docs(kit, vis):
    return any(vis.get(r, ("unknown", "unknown")) == ("public", "yes") for r in kit.repos)


def code_marker(kit, vis):
    if not kit.has_real_code:
        return "No"
    states = [vis.get(r, ("unknown", "unknown"))[0] for r in kit.repos]
    if states and all(v == "missing" for v in states):
        return "Yes (not published)"
    return "Yes"


def kit_link(kit):
    return "[%s](%s.md)" % (kit.name, kit.slug)


PULLED_TABLE_HEADING = "## Pages in this book"        # written by tools/pull-docs.py into each pulled index.md
_PULLED_ROW = re.compile(r"^\|\s*\[((?:[^\]\\]|\\.)+)\]\(([^)\s]+)\)\s*\|")


def pulled_pages(root, folder):
    """The pages that tools/pull-docs.py pulled into book/30-kits/<folder>/, as [(title, path from 30-kits/)].
    Empty when <folder>/index.md does not exist (nothing pulled). The first entry is the reference index."""
    if not root:
        return []
    index = os.path.join(root, KITS_DIR, *folder.split("/"), "index.md")
    if not os.path.isfile(index):
        return []
    with open(index, encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    pages = [("Reference index", folder + "/index.md")]
    in_table = False
    for line in lines:
        if line.strip() == PULLED_TABLE_HEADING:
            in_table = True
        elif in_table and line.startswith("## "):
            break
        elif in_table:
            m = _PULLED_ROW.match(line)
            if m and not m.group(2).startswith(("http:", "https:", "#")):
                pages.append((m.group(1).replace("\\|", "|"), folder + "/" + m.group(2)))
    return pages


def pulled_list(pages):
    return ["* [%s](%s)" % (title, path) for title, path in pages]


def render_card(kit, kits_by_name, vis, root=None):
    out = [GENERATED_MARK, "", "# %s" % kit.name, ""]
    if kit.tagline and not kit.tagline_derived:
        out += ["*%s*" % kit.tagline, ""]
    out.append("* **Status:** %s ([what this means](status-vocabulary.md#%s))" % (kit.status, kit.status))
    out.append("* **Language:** %s" % (kit.language or "not recorded"))
    if kit.kind:
        out.append("* **Kind:** %s" % kit.kind)
    out.append("* **Has real code today:** %s" % code_marker(kit, vis))
    out.append("* **Source:** %s" % source_text(kit, vis))
    if kit.merged_into:
        target = kits_by_name.get(kit.merged_into)
        merged = kit_link(target) if target else kit.merged_into
        out.append("* **Registry entry:** merged into %s; this Kit's repository and crate names are unchanged" % merged)
    elif kit.section == "pending_kits":
        out.append("* **Registry entry:** pending; not yet a published Kit")
    if kit.provisional:
        out.append("* **Name:** provisional; it may change")
    out += ["", "## What it owns", ""]
    if kit.owns:
        for p in kit.owns:
            out += [p, ""]
        if kit.is_stub:
            out += ["*The registry entry for this Kit is still a short summary, so this card is brief.*", ""]
    else:
        out += ["The registry has no public-safe description for this Kit yet.", ""]
    if kit.member_links:
        parts = ["%s (module `%s`)" % (kit_link(m) if m is not None and m is not kit else name, mod)
                 for m, name, mod in kit.member_links]
        out += ["It is made up of: " + ", ".join(parts) + ".", ""]
    if kit.wont:
        out += ["## What it will not do", ""]
        out += ["* %s" % w for w in kit.wont]
        out.append("")
    if kit.related:
        out += ["## Related Kits", "", ", ".join(kit_link(r) for r in kit.related), ""]
    out += ["## Reference docs", ""]
    pulled = pulled_pages(root, "%s/reference" % kit.slug)
    if pulled:
        out += ["This Kit's own reference documentation is pulled into the book from the Kit, at the commit this book pins, "
                "so you can read it here without access to the Kit's repository. Edit it in the Kit, not here.", ""]
        out += pulled_list(pulled)
    elif has_public_docs(kit, vis):
        out.append("This Kit's own reference documentation has not been pulled into the book yet. `make docs-pull` pulls it "
                   "once the Kit has a section in `tools/docs-pull.conf`; see [Make targets](../90-reference/make-targets.md#docs-pull).")
    else:
        out.append("No reference docs yet.")
    out += ["", "---", "", "[All Kits](README.md) · [Status vocabulary](status-vocabulary.md)", ""]
    return "\n".join(out)


def grouped(kits):
    groups = []
    for status in STATUS_ORDER:
        members = [k for k in kits if k.status == status]
        if members:
            groups.append((status, members))
    return groups


def render_index(kits, kits_by_name, vis, registry_commit):
    out = [GENERATED_MARK, "", "# Kits", ""]
    out += [
        "This is the catalog of every Kit in the %s Kit registry: public or private, working or banked or archived. "
        "Each Kit has a status card. A Kit that is not public yet is listed anyway, because a catalog that hid its "
        "unfinished parts would not be honest about the platform." % OWNER, "",
        "The catalog is generated from the registry, not written by hand, so it cannot drift from it. The pages are "
        "committed to this repository so you can read them without access to the registry. A link to a repository "
        "appears only when that repository is public today.", "",
    ]
    if registry_commit:
        out += ["Generated from registry commit %s." % registry_commit, ""]
    counts = ", ".join("%d %s" % (len(m), s) for s, m in grouped(kits))
    public = sum(1 for k in kits if any(vis.get(r, ("unknown", "unknown"))[0] == "public" for r in k.repos))
    out += ["%d Kits: %s. %s." % (len(kits), counts, "None has a public repository today" if public == 0 else
            "%d of them %s a public repository today" % (public, "has" if public == 1 else "have")), ""]
    out += [
        "## How to read the cards", "",
        "* **Status** says how real the Kit is, judged by evidence (code and tests), not by intent. "
        "See the [status vocabulary](status-vocabulary.md).",
        "* **Has real code today** is *Yes* for the statuses alpha, pre-release and stable. It says nothing about whether "
        "you can read the code: that depends on the Source line.",
        "* **Kind** is the registry's own label for the Kit (cross-platform, hybrid, substrate, infrastructure or core). "
        "It is not defined further yet.",
        "* Some cards are brief because the registry entry behind them is brief. They say so.",
        "* A Kit that was merged into another keeps its card and says which. "
        "Things that are not registered Kits, and this book itself, are on [Not in the registry](not-in-the-registry.md).", "",
    ]
    for status, members in grouped(kits):
        out += ["## %s" % status, "", STATUS_WORDING[status], "",
                "| Kit | Language | Kind | What it is | Has real code today | Repository |",
                "|---|---|---|---|---|---|"]
        for k in members:
            what = k.tagline or "No public tagline yet."
            if k.merged_into:
                target = kits_by_name.get(k.merged_into)
                what += " Merged into %s." % (kit_link(target) if target else k.merged_into)
            out.append("| %s | %s | %s | %s | %s | %s |" % (
                kit_link(k), md_escape_cell(k.language or "-"), md_escape_cell(k.kind or "-"), md_escape_cell(what),
                code_marker(k, vis), source_cell(k, vis)))
        out.append("")
    out += ["## Regenerating", "",
            "Maintainers regenerate this folder with `make docs-catalog`; see [Make targets](../90-reference/make-targets.md#docs-catalog).", ""]
    return "\n".join(out)


def render_vocabulary(kits):
    used = dict((s, [k for k in kits if k.status == s]) for s in STATUS_ORDER)
    out = [GENERATED_MARK, "", "# Status vocabulary", "",
           "Every Kit card carries one status. The test for a status is evidence, not intent: what the repository holds "
           "today (code, tests, a published version), not what is planned.", ""]
    for status in STATUS_ORDER:
        out += ["## %s" % status, "", STATUS_WORDING[status], ""]
        members = used[status]
        if members:
            out += ["Kits with this status: " + ", ".join(kit_link(k) for k in members) + ".", ""]
        else:
            out += ["No Kit has this status today.", ""]
    out += ["---", "", "[All Kits](README.md)", ""]
    return "\n".join(out)


