#!/usr/bin/env python3
"""Generate the Kit catalog in book/30-kits/ from the Kit registry.  MAINTAINER TOOL.

    python3 tools/gen-catalog.py --registry PATH [--registry-commit SHA] [--offline]
    make docs-catalog REGISTRY=PATH [REGISTRY_COMMIT=SHA] [OFFLINE=1]

The registry (kits.yaml) lives in a private repository. This tool turns it into Markdown pages that are COMMITTED
to this repository, so readers never need the registry, and `make docs` never runs this tool. Only the person who
regenerates the catalog needs the registry, `gh` (unless --offline) and PyYAML:

    python3 -m pip install pyyaml

What it writes (all under book/30-kits/ unless said otherwise)
  <slug>.md               one status card per Kit in the registry (kits, merged_kits and pending_kits, in file order)
  README.md               the catalog index: every Kit by status group, with the "Has real code today" marker
  status-vocabulary.md    what each status means
  not-in-the-registry.md  candidates that are NOT registered Kits (so not in the catalog), and this book
  (a card's "Reference docs" section, and the Application Kit's section there, list the pages that tools/pull-docs.py
   has pulled into book/30-kits/<slug>/reference/ and book/30-kits/application-kit/, when those exist)
  ../SUMMARY.md           only the block between <!-- catalog:start --> and <!-- catalog:end --> (added if missing)
  ../../tools/kit-visibility.tsv   who is public, as `gh` answered on the day (so --offline can reproduce the output);
                          keyed by Kit name, it never records a repository slug or an org name

Public safety. The book is meant to become public, and the registry is full of internal context. Nothing is copied
across unchanged. Prose goes through sanitise_text(): parentheticals and whole sentences that mention people, roles,
agents, tickets, hostnames, local paths, vault notes, Jira, dates or internal program names are DROPPED (never
paraphrased), and every rendered page is scanned again before it is written (assert_page_clean); a leak raises
LeakError and nothing is written. A repository link appears only for a repository that `gh` reported as public.

Idempotent: the same registry and the same kit-visibility.tsv give byte-identical files. No timestamps are written
into the pages. Python 3.8+, standard library plus PyYAML.
"""
