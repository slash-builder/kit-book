def render_all(kits, vis, registry_commit, root=None):
    kits_by_name = dict((k.name, k) for k in kits)
    pages = {"README.md": render_index(kits, kits_by_name, vis, registry_commit),
             "status-vocabulary.md": render_vocabulary(kits),
             "not-in-the-registry.md": render_not_in_registry(vis, root)}
    for k in kits:
        pages["%s.md" % k.slug] = render_card(k, kits_by_name, vis, root)
    return pages


_LINK_TARGET = re.compile(r"\]\([^)]*\)")


def assert_page_clean(name, text):
    """Last line of defence: scan the rendered page the way check-public would. Link targets are checked by make docs."""
    scan = text.replace(GENERATED_MARK, "")
    scan = _LINK_TARGET.sub("]()", scan)
    scan = re.sub(r"\[[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+\]", "[repo]", scan)      # the link text of a public repo, org/repo
    leaks = find_leaks(scan)
    if leaks:
        raise LeakError("%s would publish: %s" % (name, "; ".join("%s: %r" % l for l in leaks)))


