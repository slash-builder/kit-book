def summary_block(kits):
    """The marker lines are indented like the entries so that Markdown keeps them inside the Kits list item."""
    lines = ["  " + SUMMARY_START,
             "  - [Status vocabulary](30-kits/status-vocabulary.md)",
             "  - [Not in the registry](30-kits/not-in-the-registry.md)"]
    for _, members in grouped(kits):
        for k in members:
            lines.append("  - [%s](30-kits/%s.md)" % (k.name, k.slug))
    lines.append("  " + SUMMARY_END)
    return "\n".join(lines)


_BLOCK = re.compile(r"^[ \t]*" + re.escape(SUMMARY_START) + r".*?" + re.escape(SUMMARY_END) + r"[ \t]*$", re.M | re.S)


def update_summary(text, kits):
    """Replace only the marked block (adding it after the Kits index entry if the markers are missing)."""
    block = summary_block(kits)
    has_start, has_end = SUMMARY_START in text, SUMMARY_END in text
    if has_start != has_end or (has_start and text.index(SUMMARY_START) > text.index(SUMMARY_END)):
        raise SystemExit("error: SUMMARY.md has a catalog marker without its partner (or in the wrong order); fix by hand.")
    if has_start:
        return _BLOCK.sub(lambda m: block, text, count=1)
    m = re.search(r"^- \[Kits\]\(30-kits/README\.md\)[ \t]*$", text, re.M)
    if not m:
        raise SystemExit("error: SUMMARY.md has no '- [Kits](30-kits/README.md)' line to put the catalog block under.")
    return text[:m.end()] + "\n" + block + text[m.end():]


def write_text(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not text.endswith("\n"):
        text += "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def write_all(root, pages, kits):
    out_dir = os.path.join(root, KITS_DIR)
    for name, text in pages.items():
        write_text(os.path.join(out_dir, name), text)
    removed = []
    for name in sorted(os.listdir(out_dir)):                      # a Kit that left the registry loses its card
        path = os.path.join(out_dir, name)
        if name.endswith(".md") and name not in pages:
            with open(path, encoding="utf-8") as fh:
                first = fh.readline().rstrip("\n")
            if first == GENERATED_MARK:
                os.remove(path)
                removed.append(name)
    summary_path = os.path.join(root, "book", "SUMMARY.md")
    with open(summary_path, encoding="utf-8") as fh:
        summary = fh.read()
    write_text(summary_path, update_summary(summary, kits))
    return removed


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate the Kit catalog (book/30-kits/) from the Kit registry.")
    ap.add_argument("--registry", default=os.environ.get("KITS_REGISTRY"),
                    help="path to kits.yaml (default: $KITS_REGISTRY)")
    ap.add_argument("--registry-commit", default=None, help="commit of the registry this was generated from (printed in the index)")
    ap.add_argument("--offline", action="store_true", help="do not call gh; use %s as it is" % VISIBILITY_FILE)
    ap.add_argument("--root", default=ROOT, help="repository root (default: this repository)")
    ap.add_argument("--gh", default="gh", help="the GitHub CLI command (default: gh)")
    ap.add_argument("--today", default=None, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)

    require_yaml()
    if not args.registry:
        sys.exit("error: say where the registry is: --registry PATH, or set KITS_REGISTRY.")
    commit = None
    if args.registry_commit:
        if not re.match(r"^[0-9a-fA-F]{7,40}$", args.registry_commit):
            sys.exit("error: --registry-commit must be a hex commit id (7 to 40 characters).")
        commit = args.registry_commit[:7].lower()
    today = args.today or datetime.datetime.now(datetime.timezone.utc).date().isoformat()

    kits = load_kits(args.registry)
    tsv = os.path.join(args.root, VISIBILITY_FILE)
    vis, rows, warnings = resolve_visibility(kits, tsv, args.offline, args.gh, today)
    pages = render_all(kits, vis, commit, args.root)
    for name, text in pages.items():
        assert_page_clean(name, text)
    if rows is not None:
        write_visibility(tsv, rows)
    removed = write_all(args.root, pages, kits)

    for w in warnings:
        sys.stderr.write("warning: %s\n" % w)
    by_status = ", ".join("%d %s" % (len(m), s) for s, m in grouped(kits))
    by_vis = {}
    for _, repo in repos_to_check(kits):
        by_vis[vis[repo][0]] = by_vis.get(vis[repo][0], 0) + 1
    print("gen-catalog: %d Kit cards (%s)" % (len(kits), by_status))
    print("gen-catalog: repositories: %s" % ", ".join("%d %s" % (n, v) for v, n in sorted(by_vis.items())))
    print("gen-catalog: wrote %d pages in %s%s" % (len(pages), KITS_DIR, "; removed " + ", ".join(removed) if removed else ""))
    if rows is not None:
        print("gen-catalog: recorded visibility in %s" % VISIBILITY_FILE)
    return 0


if __name__ == "__main__":
    sys.exit(main())
