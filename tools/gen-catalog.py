def find_leaks(text):
    """Return [(label, matched text)] for everything in `text` that must not be public."""
    found = []
    for label, rx in FORBIDDEN:
        for m in rx.finditer(text):
            found.append((label, m.group(0)))
    return found


_SENTENCE_SPLIT = re.compile(r"(?<!\bvs\.)(?<!\be\.g\.)(?<!\bi\.e\.)(?<!\betc\.)(?<=[.!?])\s+(?=[A-Z0-9`\"'(\[*])")
_PAREN = re.compile(r"\s*\(([^()]*)\)")
_STUB_PREFIX = re.compile(r"^STUB ENTRY[^.]*\.\s*")
# Wording that is true of the registry on the day it was written but not of a book that stays around. The first is a
# Kit that has been renamed (the registry header says so); the second is a "newest kit" claim that goes stale.
RENAMES = [(re.compile(r"\bAI Kit\b"), "Inference Kit"),
           (re.compile(r"\bis the newest kit:\s*"), "covers ")]
# Sentences that tell the registry's history rather than describe the Kit. Always dropped, and not counted as the lead
# sentence of a paragraph.
_HISTORY = re.compile(r"^(?:Added|Renamed)\b|\badmitted\b|\bReclassified\b", re.I)


def is_stub(text):
    return bool(text) and text.lstrip().startswith("STUB ENTRY")


def _owner_wording(text):
    text = re.sub(r"\bLockamy Studios'?s?\b", OWNER, text)
    text = re.sub(r"\b[Tt]he studio's\b", OWNER + "'s", text)
    text = re.sub(r"\b[Tt]he studio\b", OWNER, text)
    return text


def _dashes(sentence):
    """Em dashes are not used in this book: one dash in a sentence becomes a colon, two or more become commas."""
    n = sentence.count("\u2014") + sentence.count(" -- ")
    sep = ": " if n == 1 else ", "
    return re.sub(r"\s*(?:\u2014| -- )\s*", sep, sentence)


def sanitise_text(text, lead_required=False):
    """One paragraph (or one tagline, or one list item) in, public-safe text out. May be empty.

    1. Whitespace is collapsed (a line break after a slash joins without a space); the registry's "STUB ENTRY ... pending."
       marker is removed; "Lockamy Studios" and "the studio" become SlashBuilder; renamed Kits get their current name.
    2. A parenthetical that contains anything in FORBIDDEN is removed.
    3. Every remaining sentence that contains anything in FORBIDDEN is dropped whole.
    4. With lead_required (used for description paragraphs): if the FIRST sentence is dropped the whole paragraph goes,
       because what is left would be commentary on something the reader is not shown.
    """
    if not text:
        return ""
    text = re.sub(r"/[ \t]*\n[ \t]*", "/", str(text))
    text = " ".join(text.split())
    text = _STUB_PREFIX.sub("", text)
    text = _owner_wording(text)
    prev = None
    while prev != text:
        prev = text
        text = _PAREN.sub(lambda m: "" if find_leaks(m.group(1)) else m.group(0), text)
    for rx, new in RENAMES:
        text = rx.sub(new, text)
    sentences = [s for s in _SENTENCE_SPLIT.split(text.strip()) if s and not _HISTORY.search(s)]
    if lead_required and sentences and find_leaks(sentences[0]):
        return ""
    kept = [_dashes(s) for s in sentences if not find_leaks(s)]
    out = " ".join(kept).strip()
    out = re.sub(r"\s+([,;:])", r"\1", out)
    out = re.sub(r"\s+(\.)(?=\s|$)", r"\1", out)
    return out


def paragraphs(text, limit):
    """The first `limit` paragraphs of `text` (blank-line separated), each sanitised; empty ones are skipped."""
    if not text:
        return []
    raw = [p for p in re.split(r"\n\s*\n", str(text).strip()) if p.strip()]
    out = []
    for p in raw[:limit]:
        clean = sanitise_text(p, lead_required=True)
        if not clean:
            break          # a later paragraph leans on the one before it; do not show it on its own
        out.append(clean)
    return out


def one_line(text):
    """A tagline: sanitised and on one line."""
    return sanitise_text(text)


def md_escape_cell(text):
    return text.replace("|", "\\|")


