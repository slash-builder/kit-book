def require_yaml():
    if yaml is None:
        sys.exit(INSTALL_HINT)


def slugify(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def parse_repo(url):
    """'https://github.com/org/repo(.git)' -> 'org/repo', or None when it is not a GitHub repository URL."""
    if not url:
        return None
    m = re.match(r"^https://github\.com/([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+?)(?:\.git)?/?$", str(url).strip())
    return "%s/%s" % (m.group(1), m.group(2)) if m else None


def read_header(registry_path):
    """The leading comment block of the registry file, without the leading '# '."""
    lines = []
    with open(registry_path, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#"):
                lines.append(line.rstrip("\n")[2:] if line.startswith("# ") else line.rstrip("\n")[1:])
            elif line.strip() == "":
                lines.append("")
            else:
                break
    return "\n".join(lines)


def parse_vocabulary(header_text):
    """The status words and the registry's own one-line definitions from the header. Warns if the wording is stale."""
    vocab = {}
    in_block = False
    for line in header_text.splitlines():
        if line.startswith("STATUS VOCABULARY"):
            in_block = True
            continue
        if in_block:
            m = re.match(r"^\s+([a-z]+(?:-[a-z]+)?)\s+(.+?)\s*$", line)
            if m:
                vocab[m.group(1)] = m.group(2)
            else:
                break
    return vocab


def check_vocabulary(vocab, statuses_used):
    """Fail if the registry vocabulary and this tool disagree on the set of statuses; warn if a definition changed."""
    if not vocab:
        raise SystemExit("error: the registry header has no STATUS VOCABULARY block, so statuses cannot be defined.")
    if set(vocab) != set(STATUS_WORDING):
        raise SystemExit("error: the registry's status words %s differ from the ones this tool knows %s. "
                         "Update STATUS_WORDING and STATUS_ORDER in tools/gen-catalog.py."
                         % (sorted(vocab), sorted(STATUS_WORDING)))
    for word, text in vocab.items():
        if text != STATUS_REGISTRY_TEXT[word]:
            sys.stderr.write("warning: the registry now defines '%s' as %r; the wording in this tool was written "
                             "from %r. Revisit STATUS_WORDING.\n" % (word, text, STATUS_REGISTRY_TEXT[word]))
    unknown = sorted(set(statuses_used) - set(vocab))
    if unknown:
        raise SystemExit("error: Kit status %s is not in the registry's status vocabulary %s." % (unknown, sorted(vocab)))


class Kit(object):
    """One registry entry, reduced to what a card needs."""

    def __init__(self, entry, section):
        self.name = str(entry.get("display_name") or "").strip()
        if not self.name:
            raise SystemExit("error: a registry entry in '%s' has no display_name." % section)
        self.slug = slugify(self.name)
        self.section = section
        self.status = str(entry.get("status") or "").strip()
        if not self.status:
            raise SystemExit("error: %s has no status." % self.name)
        self.language = str(entry.get("language") or "").strip()
        self.kind = str(entry.get("tier") or "").strip()
        self.merged_into = str(entry.get("merged_into") or "").strip()
        self.tagline = one_line(entry.get("tagline"))
        desc = entry.get("description")
        summ = entry.get("summary")
        self.is_stub = is_stub(desc) or (not desc and is_stub(summ))
        self.owns = paragraphs(desc, 2) if desc else paragraphs(summ, 2)
        self.tagline_derived = False
        if not self.tagline and self.owns:
            # The registry tagline is missing, or was removed by the sanitiser: use the first sentence of the description.
            first = _SENTENCE_SPLIT.split(self.owns[0])[0]
            if len(first) <= 240:
                self.tagline = first
                self.tagline_derived = True
        self.wont = []
        for item in entry.get("scope_out") or []:
            clean = sanitise_text(item)
            if clean:
                self.wont.append(clean[0].upper() + clean[1:])
        self.related_raw = [str(r) for r in (entry.get("related_kits") or [])]
        self.repo_url = entry.get("repo")
        self.repos = []
        own = parse_repo(self.repo_url)
        if own:
            self.repos.append(own)
        self.members = []
        self.member_repos = []      # [(name of the member, org/repo)]; the name labels the repository in the visibility file
        for m in entry.get("member_repos") or []:
            slug = parse_repo(m.get("repo"))
            if slug and slug not in self.repos:
                self.repos.append(slug)
            if slug:
                self.member_repos.append((str(m.get("was") or self.name).strip(), slug))
            self.members.append((str(m.get("was") or "").strip(), str(m.get("module") or "").strip()))
        self.notes = str(entry.get("notes") or "")
        self.provisional = bool(re.search(r"NAME IS PROVISIONAL|name is provisional", self.notes))
        self.related = []          # filled by resolve_related()
        self.member_links = []     # [(Kit or None, name, module)], filled by resolve_related()

    @property
    def has_real_code(self):
        return self.status in REAL_CODE_STATUSES


def load_kits(registry_path):
    require_yaml()
    if not os.path.isfile(registry_path):
        raise SystemExit("error: no registry file at %s" % registry_path)
    with open(registry_path, encoding="utf-8") as fh:
        data = yaml.safe_load(fh) or {}
    header = read_header(registry_path)
    kits = []
    for section in ("kits", "merged_kits", "pending_kits"):
        for entry in data.get(section) or []:
            kits.append(Kit(entry, section))
    if not kits:
        raise SystemExit("error: the registry has no Kits (expected 'kits:' as a list).")
    seen = {}
    for k in kits:
        if k.slug in seen:
            raise SystemExit("error: two registry entries produce the page name '%s': %s and %s."
                             % (k.slug, seen[k.slug].name, k.name))
        seen[k.slug] = k
    vocab = parse_vocabulary(header)
    check_vocabulary(vocab, [k.status for k in kits])
    # A Kit's name is provisional if its notes say so, or the registry header says "<Name> (..., provisional name)".
    flat = " ".join(header.split())
    for k in kits:
        if re.search(re.escape(k.name) + r" \([^)]*provisional name\)", flat):
            k.provisional = True
    resolve_related(kits)
    return kits


def resolve_related(kits):
    """related_kits entries ('storage-kit (why)', 'digital-zen') -> the cards they name. Non-Kits are skipped."""
    by_slug = dict((k.slug, k) for k in kits)
    by_repo = {}
    for k in kits:                                     # a Kit's own repository name, first one wins
        own = parse_repo(k.repo_url)
        if own:
            by_repo.setdefault(own.split("/")[1].lower(), k)
    for k in kits:
        for repo in k.repos:
            by_repo.setdefault(repo.split("/")[1].lower(), k)
    for k in kits:
        seen = []
        for ref in k.related_raw:
            token = ref.split(" (")[0].strip().lower()
            target = by_slug.get(token) or by_repo.get(token)
            if target is not None and target is not k and target not in seen:
                seen.append(target)
        k.related = seen
        k.member_links = [(by_slug.get(slugify(was)), was, mod) for was, mod in k.members]


