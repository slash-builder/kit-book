def banner_comment(entry, src):
    return ("%s from %s at %s (%s). Do not edit by hand: edit it in the Kit, then run make docs-pull. -->"
            % (GENERATED_PREFIX, entry.name, entry.short, src))


def banner_quote(entry):
    return "> Reference page pulled from %s at commit %s. Edit it in the Kit, not here." % (entry.name, entry.short)


def add_banner(text, entry, src):
    lines = text.splitlines()
    at = None
    for i, (line, code) in enumerate(split_fenced(lines)):
        if not code and re.match(r"^# ", line):
            at = i
            break
    if at is None:                                       # no title line: the quote goes first
        lines = [banner_quote(entry), ""] + lines
    else:                                                # the quote goes right under the title
        lines[at + 1:at + 1] = ["", banner_quote(entry)]
        if at + 3 < len(lines) and lines[at + 3].strip():
            lines.insert(at + 3, "")
    return banner_comment(entry, src) + "\n\n" + "\n".join(lines).strip("\n") + "\n"


def pages_table(pages):
    rows = ["| Page | What it covers |", "|---|---|"]
    for p in pages:
        rows.append("| [%s](%s) | %s |" % (p.title.replace("|", "\\|"), p.dest, description(p.text)))
    return "\n".join(rows)


