def disk_state(root, dest):
    """Generated files currently under a destination folder: path relative to root -> bytes."""
    found = {}
    base = os.path.join(root, *dest.split("/"))
    for dirpath, _dirs, files in os.walk(base):
        for f in sorted(files):
            full = os.path.join(dirpath, f)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            with open(full, "rb") as fh:
                data = fh.read()
            under_assets = rel.startswith(dest + "/" + ASSETS + "/")
            if under_assets or (f.endswith(".md") and data.startswith(GENERATED_PREFIX.encode("utf-8"))):
                found[rel] = data
    return found


def write_results(root, results, summary_new):
    removed = []
    for r in results:
        for rel in sorted(set(disk_state(root, r.dest)) - set(r.files)):
            os.remove(os.path.join(root, *rel.split("/")))
            removed.append(rel)
        for rel, data in sorted(r.files.items()):
            full = os.path.join(root, *rel.split("/"))
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "wb") as fh:
                fh.write(data)
        base = os.path.join(root, *r.dest.split("/"))
        for dirpath, dirs, files in os.walk(base, topdown=False):      # empty folders left behind
            if not os.listdir(dirpath) and dirpath != base:
                os.rmdir(dirpath)
    if summary_new is not None:
        with open(os.path.join(root, "book", "SUMMARY.md"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(summary_new)
    return removed


def differences(root, results, summary_new):
    """(path, kind, detail lines) for everything on disk that a fresh pull would change."""
    diffs = []
    for r in results:
        have = disk_state(root, r.dest)
        for rel in sorted(set(have) | set(r.files)):
            if rel not in r.files:
                diffs.append((rel, "stale (the Kit no longer has it)", []))
            elif rel not in have:
                diffs.append((rel, "missing", []))
            elif have[rel] != r.files[rel]:
                try:
                    d = list(difflib.unified_diff(have[rel].decode("utf-8").splitlines(), r.files[rel].decode("utf-8").splitlines(),
                                                  "committed", "fresh pull", lineterm="", n=0))[:12]
                except UnicodeDecodeError:
                    d = ["(binary file differs)"]
                diffs.append((rel, "differs", d))
    if summary_new is not None:
        with open(os.path.join(root, "book", "SUMMARY.md"), encoding="utf-8") as fh:
            cur = fh.read()
        if cur != summary_new:
            diffs.append(("book/SUMMARY.md", "differs (the docs-pull block)",
                          list(difflib.unified_diff(cur.splitlines(), summary_new.splitlines(), "committed", "fresh pull",
                                                    lineterm="", n=0))[:12]))
    return diffs


