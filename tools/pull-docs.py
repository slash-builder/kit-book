#!/usr/bin/env python3
"""Pull each Kit's own reference documentation into the book.  MAINTAINER TOOL (standard library only).

    python3 tools/pull-docs.py             pull into the book (this is `make docs-pull`, which then runs the checks)
    python3 tools/pull-docs.py --check     re-pull in memory and fail if the committed pages differ (`make docs-pull-check`)

The Kits keep their documentation next to their code, so it versions with the code. The book needs it INSIDE the
book, so that a reader never needs the Kit's repository. This tool copies the pages out of a fetched Kit
(.kits/<name>/, pinned by kits.lock) into the book as GENERATED pages, and the pages are COMMITTED, so readers
never need `make setup` (and never need access to a private repository) to read them.

What it reads
  kits.lock           which Kits exist, at which commit, public or private
  tools/docs-pull.conf   per Kit: the destination folder, which source files to pull, their order in the contents
  .kits/<name>/       the fetched Kit. Its .fetched file must equal the commit in kits.lock, or nothing is written

What it writes (per Kit, under the destination folder from the configuration)
  index.md            the Kit's reference index, from its docs/README.md, plus a generated table of the pages
  <page>.md           one page per pulled source file; names are lower case, `docs/` is dropped
  assets/...          images the pages use, copied (an image that cannot be found is dropped with a note)
  ../SUMMARY.md       only the block between <!-- docs-pull:start --> and <!-- docs-pull:end -->, under the
                      "# Kit reference" part (see summary_block for why it is a part of its own)

Every pulled page starts with a banner comment and carries a visible line under its title:
"Reference page pulled from <kit> at commit <sha7>. Edit it in the Kit, not here."

Link rewriting (Kit text is never edited in any other way)
  external (http:, https:, mailto:) and same-page #anchors     left as they are
  relative link to a pulled page (or to a folder whose README   becomes a relative link to the pulled copy; the
    is pulled, or to docs/README.md)                            #anchor is kept (headings are not changed)
  relative link to the Kit's root README.md or CONTRIBUTING.md,  becomes a link to the Kit's catalog entry in the book
    Kit is PRIVATE and the section sets `home`                  (so "Repository home" and "Contributing" go somewhere)
  relative link to anything not pulled, Kit is PRIVATE         becomes plain text (the link text stays)
  relative link to anything not pulled, Kit is PUBLIC          becomes a GitHub blob/tree URL at the pinned commit
  link that leaves the Kit, or points at nothing                plain text, and listed as a warning (fix it in the Kit)
  image that exists in the Kit                                  copied to assets/ and linked there
  image that does not exist                                     dropped, with a visible note
Code blocks and code spans are never touched.

Idempotent and deterministic: the same Kit commit and configuration give byte-identical files; nothing carries a time.
"""
