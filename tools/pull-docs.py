def run(root, lock_path, conf_path, kits_dir, check, out=print):
    lock, confs = read_lock(lock_path), read_conf(conf_path)
    for name in confs:
        if name not in lock:
            raise PullError("tools/docs-pull.conf has a section [%s] but kits.lock does not list that Kit." % name)
    names = [n for n in lock if n in confs]
    if not names:
        out("pull-docs: no Kit in kits.lock has a section in tools/docs-pull.conf; nothing to pull.")
        return 0
    results, skipped = [], []
    for n in names:
        if check and not os.path.isdir(os.path.join(kits_dir, n)):
            skipped.append(n)
            continue
        results.append(pull_kit(root, lock[n], confs[n], kits_dir))
    for n in skipped:
        out("pull-docs: --check skipped %s: .kits/%s is not fetched (make setup%s to check it)."
            % (n, n, " KITS=all" if lock[n].visibility == "private" else ""))
    if not results:
        return 0
    summary_new = None
    if not skipped:                      # the nav block covers every configured Kit, so it can only be judged with all of them
        with open(os.path.join(root, "book", "SUMMARY.md"), encoding="utf-8") as fh:
            summary_new = update_summary(fh.read(), results)
    for r in results:
        for w in r.warnings:
            out("warning: %s: %s" % (r.entry.name, w))
    if check:
        diffs = differences(root, results, summary_new)
        for r in results:
            out("pull-docs: checked %s at %s: %d pages (%s)" % (r.entry.name, r.entry.short, len(r.pages),
                                                              "public" if r.public else "private"))
        if diffs:
            for rel, kind, detail in diffs:
                out("  %s: %s" % (rel, kind))
                for d in detail:
                    out("      " + d)
            out("pull-docs: %d file(s) differ from a fresh pull. Run: make docs-pull   (then commit the result)" % len(diffs))
            return 1
        out("pull-docs: the committed pages match a fresh pull.")
        return 0
    removed = write_results(root, results, summary_new)
    for r in results:
        s = r.stats
        out("pull-docs: %s at %s (%s): %d pages incl. index, %d asset(s) -> %s"
            % (r.entry.name, r.entry.short, "public" if r.public else "private", len(r.pages),
               sum(1 for f in r.files if "/%s/" % ASSETS in f), r.dest))
        out("pull-docs:   links: %d to pulled pages, %d to GitHub, %d plain text%s; images: %d copied, %d dropped"
            % (s.get("to pulled page", 0), s.get("github url", 0), s.get("plain text", 0),
               (", %d to the catalog entry" % s["to catalog entry"]) if s.get("to catalog entry") else "",
               s.get("image copied", 0), s.get("image dropped", 0)))
    if removed:
        out("pull-docs: removed %d stale page(s): %s" % (len(removed), ", ".join(removed)))
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description="Pull each Kit's reference documentation into the book.")
    ap.add_argument("--check", action="store_true",
                    help="write nothing; fail if the committed pages differ from a fresh pull (skips Kits that are not fetched)")
    ap.add_argument("--root", default=ROOT, help="repository root (default: this repository)")
    ap.add_argument("--lock", default=None, help="the lock file (default: <root>/kits.lock, or $KITS_LOCK)")
    ap.add_argument("--conf", default=None, help="the configuration (default: <root>/tools/docs-pull.conf)")
    ap.add_argument("--kits-dir", default=None, help="where the Kits are fetched (default: <root>/.kits)")
    args = ap.parse_args(argv)
    root = os.path.abspath(args.root)
    lock = args.lock or os.environ.get("KITS_LOCK") or os.path.join(root, "kits.lock")
    conf = args.conf or os.path.join(root, "tools", "docs-pull.conf")
    kits_dir = args.kits_dir or os.path.join(root, ".kits")
    try:
        return run(root, lock, conf, kits_dir, args.check)
    except PullError as e:
        sys.stderr.write("error: %s\n" % e)
        return 2


if __name__ == "__main__":
    sys.exit(main())
