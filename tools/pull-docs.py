def dest_name(src, index_src):
    """Where a source file lands, relative to the destination folder: lower case, `docs/` dropped,
    a folder's README.md named after the folder."""
    if src == index_src:
        return "index.md"
    p = src[len("docs/"):] if src.startswith("docs/") else src
    d, base = posixpath.split(p)
    if base.lower() == "readme.md" and d:
        d, base = posixpath.split(d)[0], posixpath.basename(d) + ".md"
    return posixpath.join(d, base.lower()) if d else base.lower()


def plan_pages(conf, kitdir):
    """The ordered list of source files (not counting the index) and their destination names."""
    found = []
    for pattern in conf.include:
        if pattern.startswith("/") or ".." in pattern.split("/"):
            raise PullError("[%s] include pattern leaves the Kit: %s" % (conf.name, pattern))
        for hit in sorted(glob.glob(os.path.join(kitdir, *pattern.split("/")), recursive=True)):
            rel = os.path.relpath(hit, kitdir).replace(os.sep, "/")
            if os.path.isfile(hit) and rel not in found:
                found.append(rel)
    found = [f for f in found if f != conf.index and not any(fnmatch.fnmatch(f, x) for x in conf.exclude)]
    for f in found:
        if not f.endswith(".md"):
            raise PullError("[%s] %s is not Markdown; only .md pages are pulled" % (conf.name, f))
    ordered = []
    for src, _label in conf.order:
        if src not in found:
            raise PullError("[%s] order lists %s, which the include/exclude lines do not select (or the Kit no longer has)"
                            % (conf.name, src))
        if src not in ordered:
            ordered.append(src)
    ordered += [f for f in found if f not in ordered]
    names = {}
    for src in ordered:
        n = dest_name(src, conf.index)
        if n in names or n == "index.md":
            raise PullError("[%s] %s and %s would both become %s" % (conf.name, names.get(n, "the index"), src, n))
        names[n] = src
    return ordered


