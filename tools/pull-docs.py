class LockEntry(object):
    def __init__(self, name, url, commit, visibility, role):
        self.name, self.url, self.commit, self.visibility, self.role = name, url, commit, visibility, role

    @property
    def slug(self):
        s = re.sub(r"^https://github\.com/|^git@github\.com:", "", self.url)
        return re.sub(r"(\.git)?/?$", "", s)

    @property
    def short(self):
        return self.commit[:7]


def read_lock(path):
    if not os.path.isfile(path):
        raise PullError("no kits.lock at %s" % path)
    entries = {}
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            f = line.split()
            if len(f) < 5:
                raise PullError("kits.lock: a line needs name, url, commit, visibility and role: %r" % line)
            entries[f[0]] = LockEntry(*f[:5])
    return entries


class KitConf(object):
    def __init__(self, name, dest, public, index, include, exclude, order, title, nav_title, home=None):
        self.name, self.dest, self.public, self.index = name, dest, public, index
        self.home = home                      # book-relative target (with optional #anchor) for README/CONTRIBUTING links
        self.include, self.exclude, self.order = include, exclude, order       # order: list of (source path, label or None)
        self.title, self.nav_title = title, nav_title


def _lines(value):
    return [l.strip() for l in (value or "").splitlines() if l.strip() and not l.strip().startswith("#")]


def read_conf(path):
    if not os.path.isfile(path):
        raise PullError("no configuration at %s" % path)
    cp = configparser.ConfigParser(interpolation=None, delimiters=("=",), comment_prefixes=("#",),
                                   inline_comment_prefixes=None)
    cp.optionxform = str
    try:
        with open(path, encoding="utf-8") as fh:
            cp.read_file(fh)
    except configparser.Error as e:
        raise PullError("%s: %s" % (path, e))
    kits = {}
    for name in cp.sections():
        sec = cp[name]
        unknown = set(sec) - {"dest", "public", "index", "include", "exclude", "order", "title", "nav_title", "home"}
        if unknown:
            raise PullError("%s: [%s] has unknown key(s): %s" % (path, name, ", ".join(sorted(unknown))))
        dest = sec.get("dest", "").strip().strip("/")
        if not dest.startswith("book/"):
            raise PullError("%s: [%s] dest must be a folder under book/ (got %r)" % (path, name, dest))
        public = sec.get("public", "auto").strip().lower()
        if public not in ("auto", "yes", "no"):
            raise PullError("%s: [%s] public must be auto, yes or no (got %r)" % (path, name, public))
        order = []
        for item in _lines(sec.get("order")):
            src, _, label = item.partition("|")
            order.append((src.strip(), label.strip() or None))
        include = _lines(sec.get("include"))
        if not include:
            raise PullError("%s: [%s] include lists no source files" % (path, name))
        home = sec.get("home", "").strip() or None
        if home and (home.startswith("/") or ".." in home.split("#")[0].split("/") or not home.split("#")[0].endswith(".md")):
            raise PullError("%s: [%s] home must be a Markdown page under book/, written relative to book/ (got %r)" % (path, name, home))
        kits[name] = KitConf(name, dest, public, sec.get("index", "").strip() or None, include,
                             _lines(sec.get("exclude")), order, sec.get("title", "").strip() or name,
                             sec.get("nav_title", "").strip() or None, home)
    return kits


