class Rewriter(object):
    """Rewrites the links of one Kit's pages. `pulled` maps a Kit-relative source path to its destination name."""

    HOME_FILES = ("readme.md", "contributing.md")      # root files of a Kit that `home` stands in for

    def __init__(self, kitdir, entry, public, pulled, home=None, dest=None):
        self.kitdir, self.entry, self.public, self.pulled = kitdir, entry, public, pulled
        self.home, self.dest = home, dest      # home: book-relative target; dest: the Kit's folder (both set, or neither)
        self.assets = {}                      # destination name under assets/ -> bytes
        self.warnings = []
        self.stats = {"to pulled page": 0, "plain text": 0, "github url": 0, "to catalog entry": 0, "image copied": 0, "image dropped": 0}
        self.page = None
        self.page_dest = None

    # -- resolving ---------------------------------------------------------------------------------------------

    def _resolve(self, target):
        """Kit-relative normalised path, or None if it leaves the Kit."""
        path = urllib.parse.unquote(target)
        norm = posixpath.normpath(posixpath.join(posixpath.dirname(self.page), path)) if path else self.page
        if norm == ".." or norm.startswith("../") or norm.startswith("/"):
            return None
        return norm

    def _pulled_dest(self, norm):
        if norm in self.pulled:
            return self.pulled[norm]
        if os.path.isdir(os.path.join(self.kitdir, *norm.split("/"))):
            for readme in ("README.md", "readme.md"):
                cand = norm + "/" + readme
                if cand in self.pulled:
                    return self.pulled[cand]
        return None

    def _rel(self, dest):
        return posixpath.relpath(dest, posixpath.dirname(self.page_dest) or ".")

    def _warn(self, msg):
        self.warnings.append("%s: %s" % (self.page, msg))

    def _source_url(self, norm, frag):
        full = os.path.join(self.kitdir, *norm.split("/"))
        kind = "tree" if os.path.isdir(full) else "blob"
        url = "https://github.com/%s/%s/%s/%s" % (self.entry.slug, kind, self.entry.commit,
                                                 urllib.parse.quote(norm, safe="/"))
        return url + ("#" + frag if frag else "")

    # -- the classes of link -----------------------------------------------------------------------------------

    def link_target(self, raw):
        """New target for a (non-image) link: a string, or None meaning 'make it plain text'."""
        raw = raw.strip()
        if raw.startswith("<") and raw.endswith(">"):
            raw = raw[1:-1]
        if not raw or raw.startswith("#") or SCHEME_RE.match(raw):
            return raw                                   # external, same-page anchor or empty: unchanged
        path, _, frag = raw.partition("#")
        frag = urllib.parse.unquote(frag)
        norm = self._resolve(path)
        if norm is None:
            self._warn("link leaves the Kit, shown as plain text: %s" % raw)
            self.stats["plain text"] += 1
            return None
        dest = self._pulled_dest(norm)
        if dest is not None:
            self.stats["to pulled page"] += 1
            new = self._rel(dest)
            if frag:
                src_file = [s for s, d in self.pulled.items() if d == dest][0]
                if frag in anchors_of(os.path.join(self.kitdir, *src_file.split("/"))):
                    new += "#" + frag
                else:
                    self._warn("dead anchor #%s in %s; the link goes to the page without it (fix it in the Kit)" % (frag, raw))
            return new
        if not os.path.exists(os.path.join(self.kitdir, *norm.split("/"))):
            self._warn("link to a file the Kit does not have, shown as plain text: %s (fix it in the Kit)" % raw)
            self.stats["plain text"] += 1
            return None
        if self.public:
            self.stats["github url"] += 1
            return self._source_url(norm, frag)
        if self.home and self.dest and norm.lower() in self.HOME_FILES:
            # a private Kit has no page to send "Repository home" or "Contributing" to; its card in the catalog is the nearest thing
            here = posixpath.dirname(posixpath.join(self.dest, self.page_dest)) or "."
            target, _, anchor = ("book/" + self.home).partition("#")
            self.stats["to catalog entry"] += 1
            return posixpath.relpath(target, here) + ("#" + anchor if anchor else "")
        self.stats["plain text"] += 1
        return None

    def image(self, alt, raw):
        raw = raw.strip()
        if raw.startswith("<") and raw.endswith(">"):
            raw = raw[1:-1]
        if SCHEME_RE.match(raw):
            return None
        norm = self._resolve(raw.partition("#")[0])
        full = os.path.join(self.kitdir, *norm.split("/")) if norm else None
        if (norm and os.path.isfile(full) and norm.lower().endswith(IMAGE_EXTENSIONS)
                and os.path.getsize(full) <= MAX_IMAGE_BYTES):
            name = posixpath.join(ASSETS, norm[len("docs/"):] if norm.startswith("docs/") else norm)
            with open(full, "rb") as fh:
                self.assets[name] = fh.read()
            self.stats["image copied"] += 1
            return self._rel(name)
        self._warn("image not found in the Kit or not a small image file, dropped: %s" % raw)
        self.stats["image dropped"] += 1
        return False

    # -- applying them to text ---------------------------------------------------------------------------------

    @staticmethod
    def _fmt(target):
        return "<%s>" % target if re.search(r"\s", target) else target

    def _inline(self, m):
        bang, text, raw, title = m.group(1), m.group(2), m.group(3), m.group(4) or ""
        if bang:
            new = self.image(text, raw)
            if new is None:
                return m.group(0)
            if new is False:
                return "*(image not included: %s)*" % (plain_text(text) or "no description")
            return "![%s](%s%s)" % (text, self._fmt(new), title)
        new = self.link_target(raw)
        if new is None:
            return text
        if new == raw.strip() or new == raw.strip().strip("<>"):
            return m.group(0)
        return "[%s](%s%s)" % (text, self._fmt(new), title)

    def rewrite(self, page_src, page_dest, text):
        self.page, self.page_dest = page_src, page_dest
        lines = text.splitlines()
        defs, plain_labels = {}, set()
        for line, code in split_fenced(lines):                 # reference definitions first
            if not code:
                d = REF_DEF_RE.match(line)
                if d:
                    defs[d.group(2).strip().lower()] = d.group(3)
        stats, nwarn = dict(self.stats), len(self.warnings)     # a dry run: do not count or warn twice
        for label, raw in defs.items():
            if self.link_target(raw) is None:
                plain_labels.add(label)
        self.stats, self.warnings[:] = stats, self.warnings[:nwarn]
        out = []
        for line, code in split_fenced(lines):
            if code:
                out.append(line)
                continue
            d = REF_DEF_RE.match(line)
            if d:
                label = d.group(2).strip().lower()
                if label in plain_labels:
                    continue                                   # the definition goes; its uses become plain text
                new = self.link_target(d.group(3))
                out.append("%s[%s]: %s%s" % (d.group(1), d.group(2), self._fmt(new), d.group(4)) if new is not None else line)
                continue
            spans = []

            def stash(m):
                spans.append(m.group(0))
                return "\x00%d\x00" % (len(spans) - 1)
            masked = CODE_SPAN_RE.sub(stash, line)
            masked = INLINE_LINK_RE.sub(self._inline, masked)
            if plain_labels:
                masked = REF_USE_RE.sub(
                    lambda m: m.group(1) if (m.group(2) or m.group(1)).strip().lower() in plain_labels else m.group(0), masked)
            for h in HTML_REF_RE.findall(masked):
                if not SCHEME_RE.match(h) and not h.startswith("#"):
                    self._warn("an HTML link or image is not rewritten: %s" % h)
            out.append(re.sub(r"\x00(\d+)\x00", lambda m: spans[int(m.group(1))], masked))
        return "\n".join(out) + "\n"


