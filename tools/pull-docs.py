def _load_link_checker():
    spec = importlib.util.spec_from_file_location("check_links_for_pull", os.path.join(HERE, "check-links.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


_LINKS = None


def anchors_of(path):
    """The heading anchors of a Markdown file, by the same rule `make docs` uses (GitHub's slugs)."""
    global _LINKS
    if _LINKS is None:
        _LINKS = _load_link_checker()
    _LINKS._anchor_cache.pop(path, None)
    return _LINKS.anchors_of(path)


def split_fenced(lines):
    """Yield (line, in_code_block) for each line; the fence lines themselves count as code."""
    fence = None                                 # (marker char, length)
    for line in lines:
        m = FENCE_RE.match(line)
        if m:
            marker, length, rest = m.group(2)[0], len(m.group(2)), m.group(3).strip()
            if fence is None:
                fence = (marker, length)
            elif marker == fence[0] and length >= fence[1] and not rest:
                fence = None
            yield line, True
            continue
        yield line, fence is not None


def plain_text(md):
    """Inline Markdown reduced to words, for titles and descriptions. Code spans keep their backticks."""
    t = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"\1", md)
    t = re.sub(r"\[((?:[^\[\]]|\[[^\]]*\])*)\]\([^)]*\)", r"\1", t)
    t = re.sub(r"\[((?:[^\[\]]|\[[^\]]*\])*)\]\[[^\]]*\]", r"\1", t)
    t = re.sub(r"<[^>]+>", "", t)
    t = re.sub(r"(\*\*|__)", "", t)
    t = re.sub(r"(?<![\w*])\*([^*\s][^*]*)\*(?![\w*])", r"\1", t)
    return re.sub(r"\s+", " ", t).strip()


def first_heading(text):
    for line, code in split_fenced(text.splitlines()):
        if code:
            continue
        m = HEADING_RE.match(line)
        if m:
            return plain_text(m.group(2))
    return None


def _blocks_after_heading(text):
    """Paragraph-ish blocks after the first heading, outside code fences."""
    lines, seen, block, out = text.splitlines(), False, [], []
    for line, code in split_fenced(lines):
        if code:
            if block:
                out.append(block)
                block = []
            continue
        if not seen:
            seen = bool(HEADING_RE.match(line))
            continue
        if not line.strip():
            if block:
                out.append(block)
                block = []
        else:
            block.append(line)
    if block:
        out.append(block)
    return out


def _first_sentence(s):
    for m in re.finditer(r"(?<=[.!?])\s+(?=[A-Z`*\[(])", s):
        before = s[:m.start()]
        if re.search(r"\b(e\.g|i\.e|etc|vs|cf|approx|no)\.$", before):
            continue
        return s[:m.start()]
    return s


def description(text):
    """One line from the first real paragraph: skips navigation lines, quotes, tables, lists and headings."""
    for block in _blocks_after_heading(text):
        first = block[0].lstrip()
        if first.startswith(("#", ">", "|", "-", "*", "+", "<", "![", "Contents:", "---")) and not first.startswith("**"):
            continue
        if re.match(r"^\d+[.)]\s", first):
            continue
        joined = " ".join(l.strip() for l in block)
        if joined.count("·") >= 2 or joined.startswith("**[") or len(plain_text(joined)) < 20:
            continue
        s = _first_sentence(plain_text(joined))
        if len(s) > DESCRIPTION_LIMIT:
            s = s[:DESCRIPTION_LIMIT].rsplit(" ", 1)[0].rstrip(",;:") + "..."
        return s.replace("|", "\\|")
    return ""


