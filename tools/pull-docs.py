def verify_pin(entry, kits_dir):
    """Refuse unless the fetched Kit is exactly the commit kits.lock pins."""
    kitdir = os.path.join(kits_dir, entry.name)
    flag = "KITS=all" if entry.visibility == "private" else ""
    fix = ("To fix it, fetch the pinned commit and run this again:\n"
           "    make fetch %s\n(make setup %s does the same and more). The book never mixes Kit versions, "
           "so nothing was written." % (flag, flag))
    if not os.path.isdir(kitdir):
        raise PullError("%s is not fetched (.kits/%s is missing).\n%s" % (entry.name, entry.name, fix))
    marker = os.path.join(kitdir, ".fetched")
    if not os.path.isfile(marker):
        raise PullError(".kits/%s has no .fetched file, so its commit is unknown (kits.lock pins %s).\n%s"
                        % (entry.name, entry.short, fix))
    with open(marker, encoding="utf-8") as fh:
        have = fh.read().strip()
    if have != entry.commit:
        raise PullError(".kits/%s is at commit %s but kits.lock pins %s.\n%s" % (entry.name, have[:7], entry.short, fix))
    return kitdir


def read_text(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read().replace("\r\n", "\n").replace("\r", "\n").lstrip("﻿")


def pull_kit(root, entry, conf, kits_dir):
    kitdir = verify_pin(entry, kits_dir)
    public = (entry.visibility == "public") if conf.public == "auto" else (conf.public == "yes")
    res = KitResult(entry, conf, public)
    ordered = plan_pages(conf, kitdir)
    index_src = conf.index if conf.index and os.path.isfile(os.path.join(kitdir, *conf.index.split("/"))) else None
    if not ordered and not index_src:
        return res
    pulled = dict((s, dest_name(s, index_src)) for s in ordered)
    if index_src:
        pulled[index_src] = "index.md"
    labels = dict(conf.order)
    rw = Rewriter(kitdir, entry, public, pulled, home=conf.home, dest=conf.dest)

    def make(src, dest):
        text = rw.rewrite(src, dest, read_text(os.path.join(kitdir, *src.split("/"))))
        return Page(src, dest, labels.get(src), text)
    pages = [make(s, pulled[s]) for s in ordered]
    for p in pages:
        if labels.get(p.src):
            p.title = labels[p.src]

    # the index: the Kit's own docs/README.md (rewritten), then the generated table of every pulled page
    if index_src:
        index = make(index_src, "index.md")
        body = index.text.rstrip("\n")
    else:
        index = Page(None, "index.md", None, "")
        body = "# %s\n\nThe Kit has no reference index of its own; these are its pulled pages." % conf.title
    table = TABLE_HEADING + "\n\nEvery page pulled from the Kit, in reading order.\n\n" \
        + pages_table(pages)
    index.text = body + "\n\n" + table + "\n"
    index.title = first_heading(index.text) or conf.title

    out = {}
    for p in [index] + pages:
        out[posixpath.join(conf.dest, p.dest)] = add_banner(p.text, entry, p.src or "generated").encode("utf-8")
    for name, data in rw.assets.items():
        out[posixpath.join(conf.dest, name)] = data
    res.files, res.pages, res.warnings = out, [index] + pages, rw.warnings
    res.stats = rw.stats
    return res


