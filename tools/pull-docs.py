def summary_block(results):
    """The block of SUMMARY.md: one entry per Kit, its pulled pages nested under it.

    It lives in a part of its own ("# Kit reference"), not inside the catalog's list under "Kits". mdBook loses the
    first list of a list item when a second list follows an HTML comment in it, so a second block after
    <!-- catalog:end --> would silently delete the whole catalog from the table of contents (checked with mdBook 0.5.4).
    """
    lines = [SUMMARY_START]
    for r in results:
        if not r.pages:
            continue
        base = r.dest[len("book/"):]
        lines.append("- [%s](%s/index.md)" % (r.conf.nav_title or "%s reference" % r.entry.name, base))
        for p in r.pages[1:]:
            lines.append("  - [%s](%s/%s)" % (p.title.replace("[", "(").replace("]", ")"), base, p.dest))
    lines.append(SUMMARY_END)
    return "\n".join(lines)


_BLOCK = re.compile(r"^[ \t]*" + re.escape(SUMMARY_START) + r".*?" + re.escape(SUMMARY_END) + r"[ \t]*$", re.M | re.S)


def update_summary(text, results):
    block = summary_block(results)
    s, e = SUMMARY_START in text, SUMMARY_END in text
    if s != e or (s and text.index(SUMMARY_START) > text.index(SUMMARY_END)):
        raise PullError("SUMMARY.md has a docs-pull marker without its partner (or in the wrong order); fix by hand.")
    if s:
        return _BLOCK.sub(lambda m: block, text, count=1)
    part = SUMMARY_PART + "\n\n" + block + "\n\n"           # no markers yet: a new part, before "# Reference" if there is one
    m = re.search(r"^# Reference[ \t]*$", text, re.M)
    if m:
        return text[:m.start()] + part + text[m.start():]
    return text.rstrip("\n") + "\n\n" + part.rstrip("\n") + "\n"


